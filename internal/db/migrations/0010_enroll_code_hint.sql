-- 0010_enroll_code_hint.sql
-- 注册码可见性（对应后台节点详情「令牌」面板）。
--
-- 库内对注册码只存哈希（S6），因此"已签发但尚未被使用"的注册码在后台**无处
-- 可看**：管理员既确认不了它是否还有效，也拿不回它的前几位来对账——一旦
-- 界面上那份丢掉（对话框关闭即清空），就只能重新签发；而重新签发又受
-- 有效码数量上限约束，节点就卡死了。
--
-- 补一列提示位，与 node_tokens.token_hint 同思路：只存前 6 位，供后台辨认，
-- 不构成凭据（注册码本身 12 位 Crockford，6 位提示无法反推）。
ALTER TABLE enroll_codes ADD COLUMN code_hint TEXT;
