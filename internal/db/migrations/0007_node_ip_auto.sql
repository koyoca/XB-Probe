-- nodes.ip_auto：ip_v4 / ip_v6 是否允许**自动更新**。
--
-- 背景：这两个字段以前只由管理员在节点编辑面板里手填（列注释里写的"默认取上报
-- 连接的来源地址，可手动覆盖"其实一直没实现），所以节点列表上的地址栏常年是空的 ——
-- 而面板上的标签却写着"IPv4（覆盖自动探测）"，等于承诺了一个不存在的功能。
--
-- 现在有两种自动来源：
--   1. Agent 上报里带的 public_ip（它自己按 agent.public_ip_url 探测来的公网地址）；
--   2. Master 侧看到的请求来源地址（经 trusted_proxies 解析）。
--
-- 两者都可能"知道得不对"：Agent 与 Master 同机时来源地址是 127.0.0.1；
-- 前置了没有被列入 trusted_proxies 的反代时来源地址是代理地址。
-- 所以规则是：
--   * 只有**公网可路由**的地址才会被自动写入（回环/私网/链路本地一律丢弃）——
--     这一条直接堵死了"地址栏里恒显示 127.0.0.1"这个现象；
--   * 管理员手工填过（ip_auto = 0）之后，自动来源不再改动它。
--     这正是标签「覆盖自动探测」的字面兑现：手填 = 覆盖。
--
-- 默认 1（允许自动）：新节点与历史节点的地址栏都是空的，没有任何东西会被误改。
ALTER TABLE nodes ADD COLUMN ip_auto INTEGER NOT NULL DEFAULT 1;
