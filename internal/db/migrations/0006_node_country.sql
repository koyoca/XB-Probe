-- 0006_node_country.sql
--
-- 节点新增"国家/地区"字段（ISO 3166-1 alpha-2，两位大写字母），
-- 用于在节点卡片上显示国旗标识。
--
-- 为什么不复用已有的 location（0001 里的 TEXT 自由文本，如 "HK-01"/"东京"）：
--   1. location 是**管理端专用**字段，被公开 DTO 的字段黑名单挡着
--      （internal/model/dto_leak_test.go 的 forbiddenPublicKeys 含 "location"），
--      它天然不能出现在公开接口里——公开看板上的节点卡片拿不到它。
--   2. 即便放开，自由文本也无法可靠地映射到国旗（"HK-01"、"香港"、"Hong Kong"
--      三种写法都要认），把"画哪面旗"这种事交给前端做字符串猜测必然出错。
--
-- 因此新增一个**结构化**的 country 列：取值是两位国家代码，前端只做代码→旗帜的
-- 查表，不做任何语义猜测。它同时进入公开 DTO 的可收窄字段白名单（public.fields），
-- 管理员不想公开节点所在国家时可以在设置里关掉这一项。
--
-- 空值（NULL / ''）表示"未设置"：卡片上不画旗帜，而不是画一面默认旗——
-- 与项目"缺值渲染 — 而不是编一个值"的约定同源。

ALTER TABLE nodes ADD COLUMN country TEXT;
