// TestVerifySumsSignatureRejectsTamperedSums 被改过的 SHA256SUMS 必须被拒。
//
// 这是整个 6.8 的安全意义所在：攻击者控制了镜像，把某个产物的校验和
// 换成了投毒二进制的哈希——此时 SHA-256 校验会"全部通过"，
// 只有 minisign 验签能发现 SHA256SUMS 本身被改过。
func TestVerifySumsSignatureRejectsTamperedSums(t *testing.T) {
	srv := sumsServer(t, distTestSums, distTestSig, true)
	tampered := strings.Replace(distTestSums, "aaa", "aab", 1)
	err := verifySumsSignature(srv.Client(), srv.URL, []byte(tampered), distTestPub, srv.URL+"/SHA256SUMS")
	if err == nil {
		t.Fatal("被篡改的 SHA256SUMS 竟然验签通过——投毒防护完全失效")
	}
	if !strings.Contains(err.Error(), "验签失败") {
		t.Errorf("错误信息应明确指出验签失败，实际：%v", err)
	}
}

