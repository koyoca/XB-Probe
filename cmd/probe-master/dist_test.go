// TestHumanBytes 是纯展示函数，但单位算错会误导（"13 MB" 写成 "13 GB"）。
func TestHumanBytes(t *testing.T) {
	cases := []struct {
		in   int64
		want string
	}{
		{512, "512 B"},
		{1024, "1.0 KB"},
		{1536, "1.5 KB"},
		{1024 * 1024, "1.0 MB"},
		{13600000, "13.0 MB"},
		{1024 * 1024 * 1024, "1.0 GB"},
	}
	for _, c := range cases {
		if got := humanBytes(c.in); got != c.want {
			t.Errorf("humanBytes(%d) = %q，期望 %q", c.in, got, c.want)
		}
	}
}

// ---------------------------------------------------------------------------
// 6.8：SHA256SUMS 的 minisign 验签
// ---------------------------------------------------------------------------
//
// 下面这组用例的公钥/签名**由真实 minisign 0.11 生成**（与 internal/auth 的
// minisign_test.go 同一套密钥）。用自造数据测验签是没意义的——
// 按自己的理解拼出来的"签名"只会把同样的误解固化进测试里。

const (
	distTestPub = `untrusted comment: minisign public key B56B8445221E5AEE
RWTuWh4iRYRrtRxnZ4S2i+5JWAetk3dpGiNA3qnSUK2yX23mNzaLGZtv
`
	// 被签名的 SHA256SUMS 原文（逐字节一致，含末尾换行）。
	distTestSums = "aaa  probe-agent_linux_amd64\nbbb  probe-agent_windows_amd64.exe\n"
	// 对应的真实签名。
	distTestSig = `untrusted comment: signature from minisign secret key
RUTuWh4iRYRrtQJ80UjfRuItOPcFCinFlrs71EOoYfVFmKnY2Z68yRsg7Jy1ZFEzSq/oi5F3KTtLV49S7KQbJasfM2+Z1/hk8gI=
trusted comment: timestamp:1760000000 file:SHA256SUMS
2FKpRlaJSJobgpgklznVbZ4DuwoJn6S1+A0pAcbq9qk339/kmqyDKUwsYqpHSZCmJ1rgFyR78DrKne0Q1WH6Ag==
`
)

// sumsServer 起一个同时提供 SHA256SUMS 与 SHA256SUMS.minisig 的假源站。
func sumsServer(t *testing.T, sums, sig string, withSig bool) *httptest.Server {
	t.Helper()
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.HasSuffix(r.URL.Path, "/SHA256SUMS"):
			_, _ = w.Write([]byte(sums))
		case strings.HasSuffix(r.URL.Path, "/SHA256SUMS.minisig"):
			if !withSig {
				http.Error(w, "not found", http.StatusNotFound)
				return
			}
			_, _ = w.Write([]byte(sig))
		default:
			http.Error(w, "not found", http.StatusNotFound)
		}
	}))
	t.Cleanup(srv.Close)
	return srv
}

