// TestDownloadVerifiedHappyPath 验证正常下载 + 校验 + 落盘流程。
func TestDownloadVerifiedHappyPath(t *testing.T) {
	content := []byte("fake agent binary payload")
	sum := sha256.Sum256(content)
	want := hex.EncodeToString(sum[:])

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Write(content)
	}))
	defer srv.Close()

	dst := filepath.Join(t.TempDir(), "probe-agent_linux_amd64")
	got, n, err := downloadVerified(srv.Client(), srv.URL, dst, want, false)
	if err != nil {
		t.Fatalf("downloadVerified 出错: %v", err)
	}
	if got != want {
		t.Errorf("got = %s, want = %s", got, want)
	}
	if n != int64(len(content)) {
		t.Errorf("写入 %d 字节，期望 %d", n, len(content))
	}
	onDisk, err := os.ReadFile(dst)
	if err != nil {
		t.Fatalf("目标文件不存在: %v", err)
	}
	if string(onDisk) != string(content) {
		t.Error("落盘内容与源不一致")
	}
	// 临时文件不能残留。
	if _, err := os.Stat(dst + ".part"); !os.IsNotExist(err) {
		t.Error(".part 临时文件残留了")
	}
}

// TestDownloadVerifiedChecksumMismatch 是这套流程里最重要的一条：
// 校验失败时必须**不留任何文件**，并且不覆盖已有的正确文件。
//
// 为什么重要：dist 是新装 Agent 的自举来源。如果校验失败却仍把文件留在目标路径上，
// 运维很可能直接"就用那个已经下好的"，从而把被篡改的二进制分发到所有新节点。
func TestDownloadVerifiedChecksumMismatch(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte("tampered payload"))
	}))
	defer srv.Close()

	dir := t.TempDir()
	dst := filepath.Join(dir, "probe-agent_linux_amd64")
	// 预置一个"已有的正确文件"，确认失败时它不会被破坏。
	const existing = "previously verified good binary"
	if err := os.WriteFile(dst, []byte(existing), 0o755); err != nil {
		t.Fatal(err)
	}

	wrong := strings.Repeat("0", 64)
	_, _, err := downloadVerified(srv.Client(), srv.URL, dst, wrong, false)
	if err == nil {
		t.Fatal("校验和不匹配时必须返回错误")
	}
	if !strings.Contains(err.Error(), "校验和不匹配") {
		t.Errorf("错误信息应说明是校验失败，实际：%v", err)
	}
	// 已有文件必须原封不动。
	got, err := os.ReadFile(dst)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != existing {
		t.Error("校验失败时覆盖了已存在的文件——这正是必须避免的情况")
	}
	// 不能留下 .part。
	if _, err := os.Stat(dst + ".part"); !os.IsNotExist(err) {
		t.Error(".part 临时文件残留了")
	}
}

