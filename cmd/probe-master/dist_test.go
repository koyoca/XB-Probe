// TestFetchSumsParsing 验证 SHA256SUMS 的解析：兼容 sha256sum 的两种写法、
// 跳过注释与非法行、按 basename 归一化路径。
//
// 这个解析必须宽容（真实文件的格式由 `sha256sum *.exe` 生成，Windows 上还会出现
// `*` 前缀的 binary 模式），但又必须拒绝长度不对的 hash——否则会把一行说明文字
// 当成校验和，最终把某个文件"校验通过"成任意内容。
func TestFetchSumsParsing(t *testing.T) {
	body := `# This file is generated by make
a1b2c3d4e5f60718293a4b5c6d7e8f9012345678a1b2c3d4e5f60718293a4b5c  probe-agent_linux_amd64
d4c3b2a1f6e50718293a4b5c6d7e8f9012345678a1b2c3d4e5f60718293a4b5c *probe-agent_windows_amd64.exe
c0ffee00000000000000000000000000000000000000000000000000000000ff  probe-agent_freebsd_arm64

not-a-hash  probe-agent_bogus
`
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte(body))
	}))
	defer srv.Close()

	sums, err := fetchSums(srv.Client(), srv.URL)
	if err != nil {
		t.Fatalf("fetchSums 出错: %v", err)
	}
	if len(sums) != 3 {
		t.Fatalf("解析出 %d 条，期望 3 条（注释/空行/非法 hash 都应跳过）：%v", len(sums), sums)
	}
	// binary 模式的 `*` 前缀必须被去掉。
	if _, ok := sums["probe-agent_windows_amd64.exe"]; !ok {
		t.Error("未解析出 windows 产物（`*` 前缀未处理）")
	}
	if _, ok := sums["probe-agent_linux_amd64"]; !ok {
		t.Error("未解析出 linux 产物")
	}
	// 路径带目录时按 basename 归一化。
	const withDir = "c0ffee00000000000000000000000000000000000000000000000000000000ff  dist/v1.0/probe-agent_freebsd_arm64\n"
	srv2 := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte(withDir))
	}))
	defer srv2.Close()
	sums2, err := fetchSums(srv2.Client(), srv2.URL)
	if err != nil {
		t.Fatal(err)
	}
	if len(sums2) != 1 {
		t.Fatalf("带目录的条目应被 basename 归一化，得到 %v", sums2)
	}
	if _, ok := sums2["probe-agent_freebsd_arm64"]; !ok {
		t.Errorf("basename 归一化失败：%v", sums2)
	}
}

